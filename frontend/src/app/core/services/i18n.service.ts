@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly currentLanguage = signal<AppLanguage>(this.readInitialLanguage());

  readonly language = this.currentLanguage.asReadonly();
  readonly locale = computed(() => this.currentLanguage() === 'es' ? 'es-ES' : 'en-CA');

  setLanguage(language: AppLanguage) {
    this.currentLanguage.set(language);
    localStorage.setItem(STORAGE_KEY, language);
  }

  t(key: keyof typeof translations.en, params?: Record<string, string | number>): string {
    const table = translations[this.currentLanguage()];
    const fallback = translations.en[key];
    let value: string = table[key] ?? fallback ?? key;

    if (!params) return value;

    for (const [param, raw] of Object.entries(params)) {
      value = value.replaceAll(`{{${param}}}`, String(raw));
    }

    return value;
  }

  private readInitialLanguage(): AppLanguage {
    const stored = localStorage.getItem(STORAGE_KEY);
    return stored === 'es' ? 'es' : 'en';
  }
}
